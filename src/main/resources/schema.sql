CREATE TABLE API_USER(
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(255) UNIQUE,
    API_KEY VARCHAR(255) UNIQUE
);

CREATE TABLE BANK(
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(255),
    SWIFT_BIC_CODE VARCHAR(255),
    WEB VARCHAR(255),
    OWNER_ID INTEGER,
    FOREIGN KEY (OWNER_ID) REFERENCES API_USER(ID) ON DELETE NO ACTION
);

CREATE TABLE MORTGAGE(
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BANK_ID INTEGER,
    NAME VARCHAR(255),
    INTEREST_RATE_TYPE VARCHAR(25) CHECK (INTEREST_RATE_TYPE IN ('FIJO', 'MIXTO', 'VARIABLE')),
    DESCRIPTION VARCHAR(255),
    APR DECIMAL(6,3),
    FOREIGN KEY (BANK_ID) REFERENCES BANK(ID) ON DELETE CASCADE
);

CREATE TABLE MORTGAGE_ATTACHMENT(
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MORTGAGE_ID INTEGER,
    FILENAME VARCHAR(255),
    CONTENT_TYPE VARCHAR(255),
    SIZE BIGINT,
    PATH VARCHAR(1024),
    FOREIGN KEY (MORTGAGE_ID) REFERENCES MORTGAGE(ID) ON DELETE CASCADE
);

