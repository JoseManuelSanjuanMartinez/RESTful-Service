CREATE TABLE BANK(
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(255),
    SWIFT_BIC_CODE VARCHAR(255),
    WEB VARCHAR(255)
);

CREATE TABLE MORTGAGE(
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BANK_ID INTEGER,
    NAME VARCHAR(255),
    INTEREST_RATE_TYPE VARCHAR(25) CHECK (INTEREST_RATE_TYPE IN ('FIJO', 'MIXTO', 'VARIABLE')),
    DESCRIPTION VARCHAR(255),
    APR DECIMAL(6,3),
    FOREIGN KEY (BANK_ID) REFERENCES BANK(ID) ON DELETE CASCADE
);


